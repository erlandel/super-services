let currentLang = 'en';
const langBtn = document.getElementById('langBtn')!;

function applyLang() {
  const t = dict[currentLang];
  document.documentElement.setAttribute('lang', currentLang);
  document.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    const k = el.getAttribute('data-i18n');
    if (k && t[k] != null) el.textContent = t[k];
  });
  document.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach((el) => {
    const k = el.getAttribute('data-i18n-html');
    if (k && t[k] != null) el.innerHTML = t[k];
  });
  document.querySelectorAll<HTMLInputElement>('[data-i18n-ph]').forEach((el) => {
    const k = el.getAttribute('data-i18n-ph');
    if (k && t[k] != null) el.setAttribute('placeholder', t[k]);
  });
  langBtn.textContent = currentLang === 'en' ? 'ES' : 'EN';
}

try {
  const saved = localStorage.getItem('lang');
  if (saved === 'en' || saved === 'es') currentLang = saved;
  else if ((navigator.language || '').toLowerCase().startsWith('es')) currentLang = 'es';
} catch {}

applyLang();

langBtn.addEventListener('click', () => {
  currentLang = currentLang === 'en' ? 'es' : 'en';
  try { localStorage.setItem('lang', currentLang); } catch {}
  applyLang();
});
